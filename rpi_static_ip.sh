#!/usr/bin/env bash
#
# rpi_static_ip.sh - give a Raspberry Pi a static IP on first boot
#
# Writes a "network-config" file (cloud-init / Netplan v2 YAML) to the root of
# the boot partition (label "bootfs") of a Raspberry Pi OS SD card that is
# mounted on this PC.
#
#  * finds the partition with label 'bootfs' itself (mounts it with udisksctl
#    when it is plugged in but not mounted)
#  * writes a Linux text file (LF line endings, UTF-8, no BOM)
#  * idempotent: the whole file is generated and only rewritten when the content
#    differs, so running it again never appends or duplicates anything; the
#    original file is backed up once as network-config.orig
#
# Usage:
#   ./rpi_static_ip.sh -a 192.168.1.50/24 -g 192.168.1.1 [-d 1.1.1.1,8.8.8.8] [-i eth0]
#   ./rpi_static_ip.sh -a 192.168.1.50/24 -g 192.168.1.1 --dry-run
#   ./rpi_static_ip.sh ... --boot-dir /path/to/bootfs     (skip auto-detection)
#
set -euo pipefail

LABEL="bootfs"
FILE_NAME="network-config"

address=""
gateway=""
dns="1.1.1.1,8.8.8.8"
interface="eth0"
boot_dir=""
dry_run=false

usage() {
    sed -n '/^# Usage:/,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'
    exit "${1:-0}"
}

die() { echo "ERROR: $*" >&2; exit 1; }
info() { echo "==> $*"; }

valid_ipv4() {
    local ip=$1 octet
    [[ $ip =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || return 1
    IFS=. read -r -a octets <<< "$ip"
    for octet in "${octets[@]}"; do
        (( 10#$octet <= 255 )) || return 1
    done
}

# 192.168.1.50/24 -> 3232235826 24 (address as integer + prefix)
ip_to_int() {
    local a b c d
    IFS=. read -r a b c d <<< "$1"
    echo $(( (10#$a << 24) | (10#$b << 16) | (10#$c << 8) | 10#$d ))
}

same_subnet() {
    local ip1=$1 ip2=$2 prefix=$3 mask
    mask=$(( prefix == 0 ? 0 : (0xFFFFFFFF << (32 - prefix)) & 0xFFFFFFFF ))
    (( ($(ip_to_int "$ip1") & mask) == ($(ip_to_int "$ip2") & mask) ))
}

parse_args() {
    while (( $# )); do
        case $1 in
            -a|--address)   address=${2:?}; shift 2 ;;
            -g|--gateway)   gateway=${2:?}; shift 2 ;;
            -d|--dns)       dns=${2:?}; shift 2 ;;
            -i|--interface) interface=${2:?}; shift 2 ;;
            -b|--boot-dir)  boot_dir=${2:?}; shift 2 ;;
            -n|--dry-run)   dry_run=true; shift ;;
            -h|--help)      usage 0 ;;
            *)              echo "Unknown option: $1" >&2; usage 1 ;;
        esac
    done

    [[ -n $address && -n $gateway ]] || { echo "Address (-a) and gateway (-g) are required." >&2; usage 1; }

    [[ $address =~ ^([0-9.]+)/([0-9]{1,2})$ ]] || die "address must look like 192.168.1.50/24"
    local ip=${BASH_REMATCH[1]} prefix=${BASH_REMATCH[2]}
    valid_ipv4 "$ip" || die "invalid IP address: $ip"
    (( prefix >= 1 && prefix <= 32 )) || die "invalid prefix length: /$prefix"
    valid_ipv4 "$gateway" || die "invalid gateway: $gateway"
    same_subnet "$ip" "$gateway" "$prefix" || die "gateway $gateway is not in $address"
    [[ $ip != "$gateway" ]] || die "address and gateway are the same"

    local server
    IFS=, read -r -a dns_servers <<< "$dns"
    for server in "${dns_servers[@]}"; do
        valid_ipv4 "$server" || die "invalid DNS server: $server"
    done
    [[ $interface =~ ^[a-z][a-z0-9]{1,14}$ ]] || die "invalid interface name: $interface"
}

# Find (and if needed mount) the partition labelled bootfs; prints its mount point
find_boot_dir() {
    local device mount_point
    device=$(blkid -L "$LABEL" 2>/dev/null || true)
    [[ -n $device ]] || device=$(lsblk -rpno NAME,LABEL | awk -v l="$LABEL" '$2 == l { print $1; exit }')
    [[ -n $device ]] || die "no partition with label '$LABEL' found - is the SD card inserted?"

    mount_point=$(findmnt -rno TARGET -S "$device" | head -n1 || true)
    if [[ -z $mount_point ]]; then
        info "Mounting $device ..." >&2
        udisksctl mount -b "$device" >/dev/null || die "could not mount $device"
        mount_point=$(findmnt -rno TARGET -S "$device" | head -n1)
    fi
    echo "$mount_point"
}

# Refuse anything that does not look like a Raspberry Pi boot partition
check_boot_dir() {
    local dir=$1
    [[ -d $dir ]] || die "$dir is not a directory"
    [[ -f $dir/config.txt || -f $dir/cmdline.txt ]] \
        || die "$dir has no config.txt/cmdline.txt - this is not a Raspberry Pi boot partition"
    [[ -w $dir ]] || die "$dir is not writable (mounted read-only?)"
}

generate_config() {
    local server
    printf '%s\n' \
        "# Generated by rpi_static_ip.sh - static IP for $interface" \
        "network:" \
        "  version: 2" \
        "  ethernets:" \
        "    $interface:" \
        "      dhcp4: false" \
        "      addresses:" \
        "        - $address" \
        "      routes:" \
        "        - to: default" \
        "          via: $gateway" \
        "      nameservers:" \
        "        addresses:"
    for server in "${dns_servers[@]}"; do
        printf '          - %s\n' "$server"
    done
    printf '%s\n' "      optional: true"
}

main() {
    parse_args "$@"

    local content target tmp
    content=$(generate_config)$'\n'   # $(...) strips the final newline

    if $dry_run; then
        printf '%s' "$content"
        exit 0
    fi

    [[ -n $boot_dir ]] || boot_dir=$(find_boot_dir)
    check_boot_dir "$boot_dir"
    target="$boot_dir/$FILE_NAME"
    info "Boot partition: $boot_dir"

    if [[ -f $target ]] && [[ "$(cat "$target")"$'\n' == "$content" ]] && ! grep -q $'\r' "$target"; then
        info "$target is already up to date - nothing changed"
        exit 0
    fi

    if [[ -f $target && ! -f $target.orig ]]; then
        cp -- "$target" "$target.orig"
        info "Backed up the original to $target.orig"
    fi

    # Write to a temp file and rename, so an interrupted run never leaves half a file
    tmp="$boot_dir/.$FILE_NAME.tmp"
    printf '%s' "$content" > "$tmp"
    mv -f -- "$tmp" "$target"
    sync

    info "Wrote $target:"
    cat "$target"
    echo
    info "Eject the card safely: udisksctl unmount -b \$(blkid -L $LABEL)"
}

main "$@"
